// Data validation function
export const validateProduct = (product) => {
  return (
    product.id &&
    product.name &&
    product.packSize &&
    product.price > 0 &&
    product.category &&
    product.emoji
  );
};

// Validate all products
export const validateAllProducts = () => {
  const invalidProducts = allProducts.filter(p => !validateProduct(p));
  if (invalidProducts.length > 0) {
    console.error('Invalid products found:', invalidProducts);
    return false;
  }
  
  // Check for duplicate IDs
  const ids = allProducts.map(p => p.id);
  const uniqueIds = new Set(ids);
  if (ids.length !== uniqueIds.size) {
    console.error('Duplicate product IDs found');
    return false;
  }
  
  console.log('All products validated successfully');
  return true;
};
